CREATE TABLE lottery_draw (
  id BIGINT NOT NULL COMMENT '记录ID',
  game VARCHAR(3) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '彩种：DLT大乐透，SSQ双色球',
  issue VARCHAR(7) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '官方原始期号',
  next_issue VARCHAR(7) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '官方连续列表确认的下一期开奖期号，未知为空',
  draw_date DATE NOT NULL COMMENT '官方开奖日期，北京时间',
  red VARCHAR(20) NOT NULL COMMENT '前区或红球，排序逗号分隔',
  blue VARCHAR(8) NOT NULL COMMENT '后区或蓝球，排序逗号分隔',
  prizes JSON NOT NULL COMMENT '奖级单注奖金分，A前缀表示追加奖金',
  pool_cents BIGINT NULL COMMENT '开奖后奖池金额分，未知为空',
  special_state VARCHAR(8) NOT NULL COMMENT '福运奖状态：ON开启，OFF关闭，UNKNOWN待核实',
  promotion TINYINT NOT NULL DEFAULT 0 COMMENT '派奖或规则待核实：0无，1需核实',
  source VARCHAR(200) NOT NULL COMMENT '官方来源标识，不含签名参数',
  rule_version VARCHAR(32) NOT NULL COMMENT '当期兑奖规则版本',
  source_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '官方有效响应SHA256摘要',
  synced_at DATETIME(3) NOT NULL COMMENT '本期最近同步时间，北京时间',
  version INT NOT NULL DEFAULT 1 COMMENT '官方有效数据修订版本，从1递增',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间',
  created_by BIGINT NULL COMMENT '创建人ID',
  created_name VARCHAR(100) NULL COMMENT '创建人',
  updated_at DATETIME(3) NULL COMMENT '更新时间',
  updated_by BIGINT NULL COMMENT '更新人ID',
  update_name VARCHAR(100) NULL COMMENT '更新人',
  deleted_at DATETIME(3) NULL COMMENT '删除时间',
  deleted_by BIGINT NULL COMMENT '删除人ID',
  deleted_name VARCHAR(100) NULL COMMENT '删除人',
  deleted TINYINT NULL DEFAULT 0 COMMENT '删除标识，0存在1删除',
  PRIMARY KEY (id),
  UNIQUE KEY uk_lottery_draw (game,issue),
  KEY idx_lottery_draw_date (game,draw_date),
  CONSTRAINT ck_lottery_draw_deleted CHECK (deleted IS NULL OR deleted IN (0,1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='独立彩票官方开奖表';

